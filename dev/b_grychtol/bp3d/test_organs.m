load('organs.mat','organs');

left = merge_meshes(organs.BloodLeftHeart, ...
                    organs.BloodAorta, ...
                    organs.BloodLIPV, ...
                    organs.BloodLSPV, ...
                    organs.BloodRIPV, ...
                    organs.BloodRSPV, ...
                    1e-2);
left = fix_boundary(left);
stl_write(left, 'LeftBloodVolume.stl', 'txt');
call_netgen('LeftBloodVolume.stl','LeftBloodVolume.vol')
%%

right = merge_meshes(organs.BloodRightHeart, ...
                     organs.BloodSVC, ...
                     organs.BloodIVC, ...
                     organs.BloodPA, ...
                     1e-2);
right = fix_boundary(right);
stl_write(right, 'RightBloodVolume.stl', 'txt');
call_netgen('RightBloodVolume.stl','RightBloodVolume.vol')

%%
walls = merge_meshes(organs.HeartWall, ...
                     organs.Aorta, ...
                     organs.PA, ...
                     organs.IVC, ...
                     organs.SVC, ...
                     organs.LIPV, ...
                     organs.LSPV, ...
                     organs.RIPV, ...
                     organs.RSPV, ...
                     1e-2);
walls = fix_boundary(walls);
stl_write(walls, 'Walls.stl','txt');
call_netgen('Walls.stl','Walls.vol');
%%
hb = merge_meshes(walls, left, right, 1e-2);
hb = fix_boundary(hb);
stl_write(hb, 'hb.stl','txt');
call_netgen('hb.stl','hb.vol');

%%
ll = merge_meshes(organs.LungLeft, ...
                  organs.Trachea, ...
                  organs.PA, ...
                  organs.LSPV, ...
                  organs.LIPV, ...
                  1e-2);
ll = fix_boundary(ll);
stl_write(ll, 'LeftLung.stl','txt');
call_netgen('LeftLung.stl','LeftLung.vol');

%%
rl = merge_meshes(organs.LungRight, ...
                  organs.Trachea, ...
                  organs.PA, ...
                  organs.RSPV, ...
                  organs.RIPV, ...
                  1e-2);
rl = fix_boundary(rl);
stl_write(rl, 'RightLung.stl','txt');
call_netgen('RightLung.stl','RightLung.vol');
